//! Build-time generator for the CLI's embedded web UI (`mahina viz`).
//!
//!   embed_assets <src-dir> <out-dir>
//!
//! Packs every file under <src-dir> (the built `viz/dist`) into
//! <out-dir>/assets.bin and writes <out-dir>/assets.zig, which `@embedFile`s the
//! blob and slices one `File` per asset out of it. Paths are URL-shaped
//! ("/index.html", "/assets/index-….js") and sorted, so the same tree always
//! gives the same bytes. `build.zig` hands this a WriteFile copy of the tree,
//! whose content-hashed path is what makes the step re-run when an asset
//! changes. The no-UI build uses a stub with the same declarations
//! (`build.zig`, `viz_assets_stub`).

const std = @import("std");
const Io = std.Io;

const Entry = struct {
    url: []const u8,
    data: []const u8,

    fn lessThan(_: void, a: Entry, b: Entry) bool {
        return std.mem.order(u8, a.url, b.url) == .lt;
    }
};

pub fn main(init: std.process.Init) !void {
    const arena = init.arena.allocator();
    const io = init.io;

    const args = try init.minimal.args.toSlice(arena);
    if (args.len != 3) {
        std.log.err("usage: embed_assets <src-dir> <out-dir>", .{});
        return error.Usage;
    }

    var src = try Io.Dir.cwd().openDir(io, args[1], .{ .iterate = true });
    defer src.close(io);

    var entries: std.ArrayList(Entry) = .empty;
    var walker = try src.walk(arena);
    defer walker.deinit();
    while (try walker.next(io)) |e| {
        if (e.kind != .file) continue;
        const url = try std.fmt.allocPrint(arena, "/{s}", .{e.path});
        // Walker paths use the host separator; URLs always use '/'.
        std.mem.replaceScalar(u8, url, std.fs.path.sep, '/');
        const data = try e.dir.readFileAlloc(io, e.basename, arena, .limited(256 * 1024 * 1024));
        try entries.append(arena, .{ .url = url, .data = data });
    }
    std.mem.sort(Entry, entries.items, {}, Entry.lessThan);
    if (entries.items.len == 0) {
        std.log.err("{s}: no files to embed (is the web UI built?)", .{args[1]});
        return error.Empty;
    }

    var out = try Io.Dir.cwd().openDir(io, args[2], .{});
    defer out.close(io);

    var blob: std.ArrayList(u8) = .empty;
    var index: std.Io.Writer.Allocating = .init(arena);
    const w = &index.writer;
    try w.writeAll(
        \\//! Generated by tools/embed_assets.zig. Do not edit.
        \\
        \\pub const File = struct { path: []const u8, data: []const u8 };
        \\
        \\pub const embedded = true;
        \\
        \\const blob = @embedFile("assets.bin");
        \\
        \\pub const files = [_]File{
        \\
    );
    for (entries.items) |e| {
        const start = blob.items.len;
        try blob.appendSlice(arena, e.data);
        try w.print("    .{{ .path = \"{f}\", .data = blob[{d}..{d}] }},\n", .{
            std.zig.fmtString(e.url), start, blob.items.len,
        });
    }
    try w.writeAll("};\n");

    try out.writeFile(io, .{ .sub_path = "assets.bin", .data = blob.items });
    try out.writeFile(io, .{ .sub_path = "assets.zig", .data = index.written() });
}
