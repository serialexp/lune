#!/usr/bin/env bash
#
# Regenerate the vendored binschema codecs from the single schema/trace.json.
#
# One schema, two consumers, two vendored codecs:
#   - the VM (producer)  -> Zig encoder/decoder  in  src/gen/
#   - the visualiser     -> TS  decoder/encoder  in  viz/src/gen/
#
# Both are committed output, so neither `zig build` nor `vite build` depends on
# the binschema repo — this script is a dev-only tool, run by hand whenever
# schema/trace.json changes. It invokes the binschema *source* CLI (the published
# dist CLI lags behind and rejects newer --language targets), vendors the
# generated sources + their runtimes, and stamps the binschema commit they came
# from into a PROVENANCE.txt in each output dir.
#
# Usage:   tools/regen-trace-schema.sh
# Env:     BINSCHEMA_DIR   path to the binschema checkout (default ~/Projects/binschema)
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
schema="$repo_root/schema/trace.json"
zig_out="$repo_root/src/gen"
ts_out="$repo_root/viz/src/gen"
binschema_dir="${BINSCHEMA_DIR:-$HOME/Projects/binschema}"
cli="$binschema_dir/packages/binschema/src/cli/index.ts"

[ -f "$schema" ] || { echo "error: schema not found: $schema" >&2; exit 1; }
[ -f "$cli" ]    || { echo "error: binschema CLI not found: $cli (set BINSCHEMA_DIR)" >&2; exit 1; }
command -v bun >/dev/null || { echo "error: bun is required to run the binschema CLI" >&2; exit 1; }

sha="$(cd "$binschema_dir" && git rev-parse --short HEAD 2>/dev/null || echo unknown)"

stamp_provenance() {
  # $1 = output dir, $2 = generated entry filename
  cat > "$1/PROVENANCE.txt" <<EOF
Generated by tools/regen-trace-schema.sh — DO NOT EDIT BY HAND.
source schema : schema/trace.json
generated file: $2
binschema repo: $binschema_dir
binschema git : $sha
EOF
}

# --- Zig (VM producer) -----------------------------------------------------
echo ">> generating Zig from $schema -> $zig_out"
( cd "$binschema_dir" && bun "$cli" generate --language zig --schema "$schema" --out "$zig_out" )
# The CLI emits generated.zig; vendor it under a clearer name (src/traceser.zig
# imports it as gen/trace_schema.zig).
mv -f "$zig_out/generated.zig" "$zig_out/trace_schema.zig"
stamp_provenance "$zig_out" "trace_schema.zig"

# --- TypeScript (visualiser consumer) --------------------------------------
echo ">> generating TypeScript from $schema -> $ts_out"
mkdir -p "$ts_out"
( cd "$binschema_dir" && bun "$cli" generate --language ts --schema "$schema" --out "$ts_out" )
# The TS generator emits generated.ts + its runtime .ts files flat into --out.
stamp_provenance "$ts_out" "generated.ts"

echo ">> done. vendored:"
echo "   src/gen/trace_schema.zig + src/gen/binschema/*.zig    (binschema $sha)"
echo "   viz/src/gen/generated.ts + runtime *.ts               (binschema $sha)"
echo ">> remember to: zig build test --summary all   &&   (cd viz && bun run build)"
