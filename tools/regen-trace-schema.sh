#!/usr/bin/env bash
#
# Regenerate the vendored binschema Zig encoder/decoder from schema/trace.json.
#
# lune builds from the committed output under src/gen/ and has NO build-time
# dependency on the binschema repo — this script is a dev-only tool, run by hand
# whenever schema/trace.json changes. It invokes the binschema *source* CLI (the
# published dist CLI lags behind and rejects --language zig), copies the runtime
# into src/gen/binschema/, writes the generated encoder/decoder as
# src/gen/trace_schema.zig, and stamps the binschema commit it came from.
#
# Usage:   tools/regen-trace-schema.sh
# Env:     BINSCHEMA_DIR   path to the binschema checkout (default ~/Projects/binschema)
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
schema="$repo_root/schema/trace.json"
out="$repo_root/src/gen"
binschema_dir="${BINSCHEMA_DIR:-$HOME/Projects/binschema}"
cli="$binschema_dir/packages/binschema/src/cli/index.ts"

[ -f "$schema" ] || { echo "error: schema not found: $schema" >&2; exit 1; }
[ -f "$cli" ]    || { echo "error: binschema CLI not found: $cli (set BINSCHEMA_DIR)" >&2; exit 1; }
command -v bun >/dev/null || { echo "error: bun is required to run the binschema CLI" >&2; exit 1; }

echo ">> generating Zig from $schema"
( cd "$binschema_dir" && bun "$cli" generate --language zig --schema "$schema" --out "$out" )

# The CLI emits generated.zig; vendor it under a clearer name (src/traceser.zig
# imports it as gen/trace_schema.zig).
mv -f "$out/generated.zig" "$out/trace_schema.zig"

# Provenance: record exactly which binschema commit produced these files.
sha="$(cd "$binschema_dir" && git rev-parse --short HEAD 2>/dev/null || echo unknown)"
cat > "$out/PROVENANCE.txt" <<EOF
Generated by tools/regen-trace-schema.sh — DO NOT EDIT BY HAND.
source schema : schema/trace.json
binschema repo: $binschema_dir
binschema git : $sha
EOF

echo ">> done. vendored:"
echo "   src/gen/trace_schema.zig"
echo "   src/gen/binschema/*.zig"
echo "   src/gen/PROVENANCE.txt  (binschema $sha)"
echo ">> remember to: zig build test --summary all"
