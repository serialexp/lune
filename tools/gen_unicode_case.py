#!/usr/bin/env python3
"""Generate src/gen/unicode_case.zig from a vendored UnicodeData.txt.

S-C (design doc 06): mahina's `string.upper`/`string.lower` use SIMPLE (1:1) case
mapping only — one code point -> one code point, count-preserving. We pull the
Simple_Uppercase_Mapping (field 12) and Simple_Lowercase_Mapping (field 13) from
UnicodeData.txt for every assigned code point >= U+0080 (ASCII A-Z/a-z are the
branch-free fast path in the runtime, so those rows are intentionally skipped).

The active Unicode version is pinned and recorded per session (a determinism
gate); bumping it means re-vendoring a new UnicodeData.txt and re-running this.

Pure + offline: reads a local vendored file, writes a generated .zig. The build
never downloads. Reproducible — same input file => byte-identical output.

Usage:
    python3 tools/gen_unicode_case.py \\
        --version 16.0.0 \\
        --ucd vendor/ucd/16.0.0/UnicodeData.txt \\
        --out src/gen/unicode_case.zig
"""
import argparse
import sys


def parse_simple_mappings(path):
    """Return (upper, lower): dicts cp -> mapped_cp for cp >= 0x80 with a simple map."""
    upper = {}
    lower = {}
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if not line:
                continue
            fields = line.split(";")
            # 0:codepoint 1:name ... 12:simple_upper 13:simple_lower 14:simple_title
            cp = int(fields[0], 16)
            if cp < 0x80:
                continue  # ASCII handled by the runtime fast path
            su = fields[12]
            sl = fields[13]
            if su:
                upper[cp] = int(su, 16)
            if sl:
                lower[cp] = int(sl, 16)
    return upper, lower


def emit(out, version, upper, lower):
    major, minor, patch = (int(x) for x in version.split("."))
    packed = (major << 16) | (minor << 8) | patch
    lines = []
    w = lines.append
    w("//! @generated by tools/gen_unicode_case.py — DO NOT EDIT BY HAND.")
    w("//!")
    w(f"//! Simple (1:1) Unicode case mapping, pinned to Unicode {version}.")
    w("//! Source: vendored UnicodeData.txt fields 12 (Simple_Uppercase_Mapping)")
    w("//! and 13 (Simple_Lowercase_Mapping), for code points >= U+0080 (ASCII is")
    w("//! the runtime's branch-free fast path). Regenerate via the `just")
    w("//! gen-unicode` recipe when re-vendoring a new Unicode version.")
    w("")
    w(f'pub const unicode_version = "{version}";')
    w("/// Packed major<<16 | minor<<8 | patch — the value recorded as the")
    w("/// `unicode_version` session effect (see interp.zig `noteUnicodeVersion`).")
    w(f"pub const unicode_version_packed: u32 = 0x{packed:06X}; // {version}")
    w("")
    w("const Map = struct { cp: u21, to: u21 };")
    w("")

    def emit_table(name, mapping):
        w(f"/// {name} simple-case mappings, sorted by `cp` for binary search.")
        w(f"const {name} = [_]Map{{")
        for cp in sorted(mapping):
            w(f"    .{{ .cp = 0x{cp:04X}, .to = 0x{mapping[cp]:04X} }},")
        w("};")
        w("")

    emit_table("upper", upper)
    emit_table("lower", lower)

    w("fn lookup(table: []const Map, cp: u21) u21 {")
    w("    var lo: usize = 0;")
    w("    var hi: usize = table.len;")
    w("    while (lo < hi) {")
    w("        const mid = lo + (hi - lo) / 2;")
    w("        const e = table[mid];")
    w("        if (cp == e.cp) return e.to;")
    w("        if (cp < e.cp) hi = mid else lo = mid + 1;")
    w("    }")
    w("    return cp; // no simple mapping: the code point is its own case")
    w("}")
    w("")
    w("/// Simple uppercase of one code point (itself if it has no mapping).")
    w("pub fn toUpper(cp: u21) u21 {")
    w("    return lookup(&upper, cp);")
    w("}")
    w("")
    w("/// Simple lowercase of one code point (itself if it has no mapping).")
    w("pub fn toLower(cp: u21) u21 {")
    w("    return lookup(&lower, cp);")
    w("}")
    w("")
    text = "\n".join(lines)
    with open(out, "w", encoding="utf-8") as f:
        f.write(text)
    return len(upper), len(lower)


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--version", required=True, help="e.g. 16.0.0")
    ap.add_argument("--ucd", required=True, help="path to UnicodeData.txt")
    ap.add_argument("--out", required=True, help="path to write the .zig table")
    args = ap.parse_args(argv)

    upper, lower = parse_simple_mappings(args.ucd)
    nu, nl = emit(args.out, args.version, upper, lower)
    print(f"wrote {args.out}: {nu} upper, {nl} lower mappings (Unicode {args.version})")


if __name__ == "__main__":
    main(sys.argv[1:])
